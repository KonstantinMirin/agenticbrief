/** The same brief the four sibling suites use, character for character. */
const CANONICAL =
  'Q4 holiday campaign for a CPG snack brand. Channels: CTV plus digital display ' +
  'and online video. Budget: $500,000 net. Market: United States. Target demo: ' +
  'adults 25-54. Flight: November 1 - December 31, 2026. Goal: drive incremental ' +
  'household penetration and retail sales lift. Requirements: premium CTV inventory, ' +
  'brand safety controls, frequency cap 3 per week.'

/** One sentence. The floor the Writecream comparison is measured against. */
const ONE_PARAGRAPH = 'We want to run some holiday advertising for a snack brand.'

/** Words, in a sentence-shaped order, meaning nothing a brief can carry. */
const GIBBERISH = 'purple monkey dishwasher quantum bicycle'

const WRITECREAM_PATH = '/srv/ws/out/research/briefgen/out-writecream.txt'
const haveWritecream = existsSync(WRITECREAM_PATH)

/**
 * Fixed reference date. Every relative-date derivation in the engine resolves
 * against this and nothing else, which is what makes a run reproducible.
 */
const NOW = new Date('2026-08-12T00:00:00Z')

const run = (text: string, opts: Record<string, unknown> = {}): EngineAnalysis =>
  analyze(text, { now: NOW, ...opts })

/* ==================================================================== *
 * Invariants asserted on every analysis in this file
 * ==================================================================== */

/** Every span must quote the input exactly, or the UI cannot highlight it. */
function assertSpansQuoteInput(a: EngineAnalysis): void {
  for (const [key, fv] of Object.entries(a.fields)) {
    for (const s of fv.spans) {
      assert.equal(
        a.input.slice(s.start, s.end),
        s.text,
        `${key}: span [${s.start},${s.end}) does not quote the input`,
      )
      assert.ok(
        s.start >= 0 && s.end <= a.input.length && s.start < s.end,
        `${key}: span [${s.start},${s.end}) is out of range for a ${a.input.length}-char input`,
      )
    }
  }
  for (const s of a.residual) {
    assert.equal(a.input.slice(s.start, s.end), s.text, 'a residual span does not quote the input')
  }
}

/** The label contract from types.ts, on every field of every result. */
function assertLabelInvariants(a: EngineAnalysis): void {
  for (const [key, fv] of Object.entries(a.fields)) {
    if (fv.label === 'stated') {
      assert.ok(fv.spans.length >= 1, `${key}: stated with no span`)
      assert.notEqual(fv.value, undefined, `${key}: stated with no value`)
    } else if (fv.label === 'derived') {
      assert.ok(fv.rule && fv.rule.length > 10, `${key}: derived with no readable rule`)
      assert.notEqual(fv.value, undefined, `${key}: derived with no value`)
    } else if (fv.label === 'assumed') {
      assert.ok(fv.rule && fv.rule.length > 10, `${key}: assumed with no rule saying where from`)
    } else {
      assert.equal(fv.value, undefined, `${key}: missing but carries a value`)
      assert.equal(fv.spans.length, 0, `${key}: missing but carries spans`)
    }
  }
}

/** `fields` covers the whole map, always. A sparse map hides a gap. */
function assertFieldMapComplete(a: EngineAnalysis): void {
  for (const key of FIELD_KEYS) {
    assert.ok(a.fields[key] !== undefined, `${key} is absent from fields`)
  }
}

/**
 * Nothing the caller did not accept reached a payload. `offered` is the set of
 * values the engine could have supplied and did not; if one of them shows up in
 * a payload, the gate in emit.ts has a second door.
 */
function assertNoUnacceptedAssumption(a: EngineAnalysis): void {
  for (const [key, fv] of Object.entries(a.offered)) {
    assert.equal(fv.label, 'assumed', `${key} is offered but not labelled assumed`)
    assert.notEqual(
      a.fields[key]?.label,
      'assumed',
      `${key} is both offered and promoted into fields`,
    )
  }
  const accepted = a.meta.options.assumeAll || a.meta.options.assume.length > 0
  if (!accepted) {
    assert.equal(
      a.scores.labels.assumed,
      0,
      'an assumed value reached `fields` without the caller accepting a key',
    )
  }
}

function assertAllInvariants(a: EngineAnalysis): void {
  assertSpansQuoteInput(a)
  assertLabelInvariants(a)
  assertFieldMapComplete(a)
  assertNoUnacceptedAssumption(a)
}

/** How many concepts the engine actually got out of a brief. */
const populatedKeys = (a: EngineAnalysis): string[] =>
  Object.entries(a.fields)
    .filter(([, fv]) => fv.label !== 'missing')
    .map(([k]) => k)
    .sort()

const filtersOf = (a: EngineAnalysis): Record<string, unknown> =>
  (a.adcp.filters ?? {}) as Record<string, unknown>

/* ==================================================================== *
 * 1. The canonical CPG brief
 * ==================================================================== */

describe('the canonical CPG brief', () => {
  const a = run(CANONICAL)

  test('span, label, completeness and assumption invariants hold', () => {
    assertAllInvariants(a)
  })

  test("'United States' becomes countries ['US'], derived, with the rule and the span", () => {
    const c = a.fields.countries!
    assert.equal(c.label, 'derived')
    assert.deepEqual(c.value, ['US'])
    assert.match(c.rule!, /ISO 3166-1/)
    assert.equal(c.spans[0]!.text, 'United States')
  })

  test('the budget figure is stated, and a bare "$" does not state a currency', () => {
    assert.equal(a.fields.budget_total!.label, 'stated')
    assert.equal(a.fields.budget_total!.value, 500000)
    assert.equal(a.fields.budget_total!.spans[0]!.text, '$500,000')

    // '$' is the sign of the US, Canadian, Australian, New Zealand, Singapore,
    // Hong Kong and Mexican dollars. Reading it as USD is a guess, so it is
    // offered and not written — `filters.budget_range.currency` is money.
    assert.equal(a.fields.currency!.label, 'missing')
    assert.equal(a.fields.currency!.value, undefined)
    assert.equal(a.offered.currency!.label, 'assumed')
    assert.equal(a.offered.currency!.value, 'USD')
    assert.match(a.offered.currency!.rule!, /sign for the US dollar and also for/)
    assert.ok(a.warnings.some((w) => w.includes("'$' is the sign for the US dollar")))

    // The other end of the range was never stated, so it is not invented.
    assert.equal(a.fields.budget_min!.label, 'missing')
  })

  test('the flight window: end stated, start derived by carrying the year back', () => {
    assert.equal(a.fields.end_date!.label, 'stated')
    assert.equal(a.fields.end_date!.value, '2026-12-31')
    assert.equal(a.fields.start_date!.label, 'derived')
    assert.equal(a.fields.start_date!.value, '2026-11-01')
    assert.match(a.fields.start_date!.rule!, /2026 stated at the close of the range/)
  })

  test('three channels are read, in both vocabularies, with the AAMP gap recorded', () => {
    const channels = a.fields.channels!.value as Array<{
      adcp: string | null
      aamp: string | null
      surface: string
    }>
    assert.deepEqual(
      channels.map((c) => [c.surface, c.adcp, c.aamp]),
      [
        ['CTV', 'ctv', 'CTV'],
        ['digital display', 'display', 'DISPLAY'],
        ['online video', 'olv', null],
      ],
    )
    // `olv` has no AAMP ChannelType, and the engine says so rather than
    // rounding it to the nearest value that happens to exist.
    assert.ok(
      a.warnings.some((w) => w.includes('`olv`') && w.includes('no AAMP ChannelType')),
      'expected the olv -> AAMP gap to be reported',
    )
  })

  test('the audience is stated as a demo and resolves to no taxonomy identifier', () => {
    const audience = a.fields.audience_primary!
    assert.equal(audience.label, 'stated')
    const value = audience.value as {
      descriptors: Array<Record<string, unknown>>
      adcpSignalTargeting: unknown
      aampAudiencePlan: { primary: unknown }
    }
    assert.deepEqual(value.descriptors, [
      { kind: 'age_range', surface: 'adults 25-54', ageMin: 25, ageMax: 54 },
    ])
    assert.equal(value.adcpSignalTargeting, null, 'a demo phrase is not a SignalRef')
    assert.equal(value.aampAudiencePlan.primary, null, 'a demo phrase is not an AudienceRef')
  })

  test("'frequency cap 3 per week' derives 3 impressions per 168 hours", () => {
    assert.equal(a.fields.frequency_cap!.label, 'derived')
    assert.deepEqual(a.fields.frequency_cap!.value, { max_impressions: 3, period_hours: 168 })
  })

  test('THE HEADLINE: no channel split is stated, so none is emitted', () => {
    assert.equal(a.fields.channel_budget_split!.label, 'missing')
    const allocations = a.aamp.channels as Array<Record<string, unknown>>
    for (const alloc of allocations) {
      assert.equal(
        alloc.budget_pct,
        undefined,
        `${String(alloc.channel)} carries a budget_pct nobody stated`,
      )
    }
    assert.ok(
      a.warnings.some((w) => w.includes('does not distribute the budget evenly')),
      'the refusal must be explained, not silent',
    )
  })

  test('the whole AdCP get_products request, exactly', () => {
    assert.deepEqual(a.adcp, {
      buying_mode: 'brief',
      brief: CANONICAL,
      filters: {
        // No budget_range: the figure is stated and the currency is not, and
        // `currency` is the one required key of core/budget-range.json.
        start_date: '2026-11-01',
        end_date: '2026-12-31',
        countries: ['US'],
        channels: ['ctv', 'display', 'olv'],
      },
    })
  })

  test('the whole AAMP CampaignBrief, exactly', () => {
    assert.deepEqual(a.aamp, {
      description: CANONICAL,
      channels: [{ channel: 'CTV' }, { channel: 'DISPLAY' }],
      target_geo: [{ geo_type: 'COUNTRY', geo_value: 'US' }],
      flight_start: '2026-11-01',
      flight_end: '2026-12-31',
      total_budget: 500000,
      // No currency, for the same reason. CampaignBrief requires one, so the
      // model will not construct — which the transactable score reports.
      frequency_cap: { max_impressions: 3, period_hours: 168 },
    })
  })

  test('accepting the currency assumption is the only thing that puts a budget on the wire', () => {
    const accepted = run(CANONICAL, { assume: ['currency'] })
    assert.equal(accepted.fields.currency!.label, 'assumed')
    assert.deepEqual((accepted.adcp.filters as Record<string, unknown>).budget_range, {
      currency: 'USD',
      max: 500000,
    })
    assert.equal(accepted.aamp.currency, 'USD')
    assert.ok(
      accepted.warnings.some((w) => w.includes('accepted assumption, not by the brief')),
      'an accepted assumption must still announce itself',
    )
  })

  test('the scores read off the payloads, not off the labels', () => {
    assert.equal(a.scores.transactable.ok, false)
    assert.equal(a.scores.transactable.score, 5)
    assert.equal(a.scores.transactable.of, 10)
    assert.deepEqual(a.scores.transactable.missing, [
      'advertiser_id',
      'campaign_name',
      'objective',
      'currency',
      'channel_budget_split',
    ])
    assert.equal(a.scores.transactable.adcpValid, true)

    assert.deepEqual(a.scores.expressive.used, ['channels', 'countries', 'end_date', 'start_date'])
    assert.equal(a.scores.expressive.total, ADCP_FILTER_FIELD_COUNT)

    assert.equal(a.scores.fieldsTotal, FIELDS.length)
    assert.equal(a.scores.labels.assumed, 0)
    assert.equal(a.scores.labels.stated, 4)
    assert.equal(a.scores.labels.derived, 5)
  })

  test('the audience is stated and still reaches neither payload, and is ranked as a drop', () => {
    const drop = a.blockers.find((b) => b.field === 'audience_primary')
    assert.ok(drop, 'a stated-and-undeliverable audience must appear in the blocker list')
    assert.equal(drop.severity, 'drops')
    assert.equal(drop.label, 'stated')
    assert.ok(!a.carried.adcp.includes('audience_primary'))
    assert.ok(!a.carried.aamp.includes('audience_primary'))
  })

  test('blockers are ranked worst first and carry the fields.ts consequence verbatim', () => {
    assert.deepEqual(
      a.blockers.filter((b) => b.severity === 'blocks').map((b) => b.field),
      ['advertiser_id', 'campaign_name', 'objective', 'currency', 'channel_budget_split'],
    )
    assert.deepEqual(
      a.blockers.map((b) => b.rank),
      a.blockers.map((_, i) => i + 1),
    )
    const objective = a.blockers.find((b) => b.field === 'objective')!
    assert.equal(objective.consequence, FIELDS.find((f) => f.key === 'objective')!.consequence)
  })

  test('the only assumption on offer is not taken, and taking it is explicit', () => {
    assert.deepEqual(Object.keys(a.offered), ['currency'])
    assert.equal(filtersOf(a).budget_range as unknown, undefined)

    // Positive control: the accept path works, so the negative above is real.
    const accepted = run(CANONICAL, { assume: ['currency'] })
    assert.deepEqual(filtersOf(accepted).budget_range, { currency: 'USD', max: 500000 })
    assert.equal(accepted.fields.currency!.label, 'assumed')

    // Assumptions do not cascade: accepting `currency` does not make
    // `pricing_currencies` appear, because the offer for it is computed from
    // what the brief STATED, not from what the caller accepted.
    assert.equal(filtersOf(accepted).pricing_currencies, undefined)
    assert.ok(
      accepted.warnings.some((w) => w.includes('accepted assumption, not by the brief')),
      'an accepted assumption must still announce itself',
    )
  })
})

/* ==================================================================== *
 * 2. The Writecream output
 * ==================================================================== */

describe(
  'the Writecream generated brief',
  { skip: haveWritecream ? false : `fixture absent: ${WRITECREAM_PATH}` },
  () => {
    const text = readFileSync(WRITECREAM_PATH, 'utf8')
    const a = run(text)
    const paragraph = run(ONE_PARAGRAPH)

    test('the fixture is the one this test is about', () => {
      // If these stop being true the assertions below are vacuous.
      assert.ok(text.length > 9_000, `expected a long brief, got ${text.length} chars`)
      assert.match(text, /CTV \(60% of Budget/)
      assert.match(text, /Online Video \(25% of Budget/)
      assert.match(text, /Digital Display \(15% of Budget/)
      assert.match(text, /window of 14 days for display; 28 days for CTV\/OLV/)
    })

    test('span, label, completeness and assumption invariants hold on 10 KB of prose', () => {
      assertAllInvariants(a)
    })

    test('more is extracted from the long brief than from one paragraph', () => {
      const long = populatedKeys(a)
      const short = populatedKeys(paragraph)
      assert.ok(
        long.length > short.length,
        `expected more fields from the long brief, got ${long.length} against ${short.length}`,
      )
      // And not merely more of the same two: the paragraph yields only the two
      // fields every input yields.
      assert.deepEqual(short, ['brief_prose', 'buying_mode'])
      for (const key of ['countries', 'start_date', 'end_date', 'channels', 'audience_primary']) {
        assert.ok(long.includes(key), `${key} should have been extracted from the long brief`)
      }
      assert.ok(
        (filtersOf(a).channels as string[]).length >= 5,
        'the long brief names many channels; the request should carry them',
      )
    })

    test("THE POINT: Writecream's 60/25/15 does not become a stated channel split", () => {
      assert.equal(
        a.fields.channel_budget_split!.label,
        'missing',
        'a split the sentence does not bind to a channel must not be adopted',
      )
      const allocations = (a.aamp.channels ?? []) as Array<Record<string, unknown>>
      assert.ok(allocations.length > 0, 'channels were named, so allocations should exist')
      for (const alloc of allocations) {
        assert.equal(alloc.budget_pct, undefined, 'a budget_pct reached the AAMP payload')
      }
      for (const payload of [a.adcp, a.aamp]) {
        const json = JSON.stringify(payload)
        assert.ok(!json.includes('budget_pct'), 'budget_pct must not appear in either payload')
      }
      assert.ok(
        a.warnings.some((w) => w.includes('no budget split was stated')),
        'the absence must be reported, not passed over',
      )
    })

    test("Writecream's 14/28-day attribution windows reach neither payload", () => {
      for (const payload of [a.adcp, a.aamp]) {
        const json = JSON.stringify(payload).toLowerCase()
        for (const token of ['attribution', 'lookback', 'view_through', 'view-through', 'vta']) {
          assert.ok(!json.includes(`"${token}`), `${token} appears as a key in a payload`)
        }
      }
      assert.equal(a.fields.kpi_targets!.label, 'missing')
      assert.ok(
        a.warnings.some((w) => /attribution or lookback window is stated/.test(w)),
        'a stated window neither protocol can carry must be reported as a loss',
      )
    })

    test('four competing budget figures produce no budget, not a chosen one', () => {
      // $500,000 / $300k / $125k / $75k. Picking one would be the invention.
      assert.equal(a.fields.budget_total!.label, 'missing')
      assert.equal(filtersOf(a).budget_range, undefined)
      assert.equal(a.aamp.total_budget, undefined)
      assert.ok(
        a.warnings.some((w) => /budget figures were stated with no range or bound cue/.test(w)),
        'the engine must say why it emitted no budget',
      )
    })

    test('nothing is assumed, however much prose there is to assume from', () => {
      assert.equal(a.scores.labels.assumed, 0)
    })
  },
)

/* ==================================================================== *
 * 3. A brief that says almost nothing
 * ==================================================================== */

describe('a brief that states no required field', () => {
  const a = run(ONE_PARAGRAPH)

  test('invariants hold', () => {
    assertAllInvariants(a)
  })

  test('the transactable score is zero of the nine AAMP requirements', () => {
    assert.equal(a.scores.transactable.ok, false)
    assert.deepEqual(a.scores.transactable.satisfied, [])
    // The tenth check — "the get_products request validates" — does pass: a
    // request carrying buying_mode and a non-empty brief is a legal request,
    // and saying otherwise would be as dishonest as the inventions this
    // package exists to catch. Nine of the ten checks fail.
    assert.equal(a.scores.transactable.score, 1)
    assert.equal(a.scores.transactable.of, 10)
    assert.equal(a.scores.transactable.adcpValid, true)
  })

  test('the blockers name every absent required field, worst first', () => {
    assert.ok(a.blockers.length > 0, 'a brief this thin must produce blockers')
    assert.deepEqual(
      a.blockers.filter((b) => b.severity === 'blocks').map((b) => b.field),
      [
        'advertiser_id',
        'campaign_name',
        'objective',
        'start_date',
        'end_date',
        'budget_total',
        'currency',
        'channels',
        'channel_budget_split',
      ],
    )
    for (const b of a.blockers.filter((x) => x.severity === 'blocks')) {
      assert.equal(b.kind, 'aamp_required_missing')
      assert.equal(b.label, 'missing')
      assert.equal(b.consequence, FIELDS.find((f) => f.key === b.field)!.consequence)
    }
    // `blocks` sorts before `degrades`, so the fix list reads top to bottom.
    const severities = a.blockers.map((b) => b.severity)
    assert.deepEqual([...severities].sort(bySeverity), severities)
  })

  test('nothing structured reaches either payload', () => {
    assert.deepEqual(Object.keys(a.adcp).sort(), ['brief', 'buying_mode'])
    assert.deepEqual(Object.keys(a.aamp), ['description'])
    assert.equal(a.scores.expressive.usedCount, 0)
  })
})

const SEVERITY_ORDER = { blocks: 0, drops: 1, degrades: 2 } as const
const bySeverity = (x: string, y: string): number =>
  SEVERITY_ORDER[x as keyof typeof SEVERITY_ORDER] -
  SEVERITY_ORDER[y as keyof typeof SEVERITY_ORDER]

