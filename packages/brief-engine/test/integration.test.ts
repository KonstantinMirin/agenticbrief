describe('nonsense input', () => {
  const a = run(GIBBERISH)

  test('does not crash, and invariants hold', () => {
    assertAllInvariants(a)
  })

  test('every field in the map is missing except the two the call itself creates', () => {
    const populated = populatedKeys(a)
    assert.deepEqual(populated, ['brief_prose', 'buying_mode'])
    // buying_mode comes from the options and brief_prose is the input verbatim;
    // neither is a claim about the campaign.
    assert.equal(a.fields.buying_mode!.label, 'derived')
    assert.match(a.fields.buying_mode!.rule!, /AnalyzeOptions\.buyingMode, not from the brief/)
    assert.equal(a.fields.brief_prose!.value, GIBBERISH)
  })

  test('zero transactable, zero expressive, no invented filter', () => {
    assert.equal(a.scores.transactable.ok, false)
    assert.deepEqual(a.scores.transactable.satisfied, [])
    assert.equal(a.scores.expressive.usedCount, 0)
    assert.equal(a.scores.expressive.ratio, 0)
    assert.equal(a.adcp.filters, undefined)
    assert.equal(a.scores.labels.assumed, 0)
    assert.equal(a.scores.labels.missing, FIELDS.length - 2)
  })
})

describe('degenerate inputs', () => {
  test('the empty string produces a request with buying_mode and nothing else', () => {
    const a = run('')
    assertAllInvariants(a)
    assert.deepEqual(Object.keys(a.adcp), ['buying_mode'])
    assert.deepEqual(a.aamp, {})
    assert.deepEqual(a.residual, [])
    assert.equal(a.scores.transactable.adcpValid, false)
    assert.ok(
      a.scores.transactable.adcpErrors.some((e) => e.includes('brief is required')),
      'the conditional `brief` rule must fire on an empty input',
    )
    assert.equal(a.scores.labels.missing, FIELDS.length - 1)
  })

  test('whitespace only extracts nothing and claims nothing', () => {
    const a = run('   \n\t  \r\n ')
    assertAllInvariants(a)
    assert.deepEqual(populatedKeys(a), ['brief_prose', 'buying_mode'])
    assert.deepEqual(a.residual, [], 'whitespace is not residue worth quoting')
    assert.equal(a.adcp.filters, undefined)
  })

  test('a non-string input is coerced, not thrown on', () => {
    // The public API is called from a browser form; `undefined` arrives.
    const a = analyze(undefined as unknown as string, { now: NOW })
    assert.equal(a.input, '')
    assert.deepEqual(Object.keys(a.adcp), ['buying_mode'])
  })

  test('100 KB of text completes, and every span still quotes it exactly', () => {
    const unit =
      'Q4 holiday campaign for a CPG snack brand. Channels: CTV. Budget: $500,000. ' +
      'Market: United States. '
    const big = unit.repeat(Math.ceil(100_000 / unit.length)).slice(0, 100_000)
    assert.equal(big.length, 100_000)

    const started = Date.now()
    const a = run(big)
    const elapsed = Date.now() - started

    assertAllInvariants(a)
    assert.ok(elapsed < 10_000, `100 KB took ${elapsed}ms; something is quadratic`)
    assert.deepEqual(a.fields.countries!.value, ['US'])
    assert.equal(a.fields.channels!.value !== undefined, true)
    // A thousand identical figures is not a thousand budgets, and it is not one
    // budget either. The engine refuses rather than picking the first.
    assert.equal(a.fields.budget_total!.label, 'missing')
    assert.equal(filtersOf(a).budget_range, undefined)
    assert.equal(a.scores.labels.assumed, 0)
  })

  test('regex metacharacters are text, not pattern', () => {
    const input =
      'Budget: $500,000 (USD). Market: (US)|[UK]? .*+ ^$ \\d{4} (?:x) [a-z]\\ ' +
      'Flight: 2026-11-01 to 2026-12-31. Channels: CTV.'
    const a = run(input)
    assertAllInvariants(a)
    assert.equal(a.fields.budget_total!.value, 500000)
    assert.equal(a.fields.currency!.value, 'USD')
    assert.equal(a.fields.start_date!.value, '2026-11-01')
    assert.equal(a.fields.end_date!.value, '2026-12-31')
    assert.equal(a.adcp.brief, input, 'the brief must carry the metacharacters verbatim')
  })

  test('unicode, including astral characters, does not shift a span', () => {
    const input =
      'Ünïcödé brïef 🎯 for a café brand. 東京 and Köln. ' +
      'Budget: €500,000. Market: United Kingdom. Flight: 2026-11-01 to 2026-12-31. ' +
      'Channels: CTV. Café — naïve — résumé 🚀🎯.'
    const a = run(input)
    assertAllInvariants(a) // this is the assertion: every span slices back exactly
    assert.equal(a.fields.currency!.value, 'EUR')
    assert.equal(a.fields.currency!.spans[0]!.text, '€')
    assert.deepEqual(a.fields.countries!.value, ['GB'])
    assert.equal(a.adcp.brief, input)
    // The emoji is a surrogate pair; a span computed in code points rather than
    // UTF-16 units would land off by one and fail the round-trip above.
    assert.ok(input.includes('🎯'))
  })
})

