/**
 * analyze() end to end.
 *
 * The extractor suites test their own modules. This file tests the product:
 * prose in, two payloads out, every value traceable. It asserts specific
 * values, not shapes — a test that only checks "something came back" would pass
 * against a generator that invented the lot, which is the failure mode this
 * package exists to prevent.
 *
 * What is asserted, and why each section exists:
 *
 *  1. THE CANONICAL CPG BRIEF. Both payloads are deep-equalled in full, so a
 *     new key appearing in either one fails here rather than arriving at a
 *     seller unannounced. `channel_budget_split` is `missing` and stays absent
 *     from the AAMP allocations — that is the headline assertion of the file.
 *
 *  2. THE WRITECREAM OUTPUT. A real 10.4 KB brief generated by the best tool on
 *     the market, which invented a 60/25/15 channel split and 14/28-day
 *     attribution windows and printed them as requirements. Fed through this
 *     engine, more is extracted than from one paragraph AND the 60/25/15 does
 *     not become a stated split, because the engine only binds a percentage to
 *     a channel when the sentence actually binds them.
 *
 *  3. A BRIEF THAT SAYS ALMOST NOTHING. Low transactable score, blockers naming
 *     every absent required field.
 *
 *  4. NONSENSE, EMPTY, WHITESPACE, 100 KB, REGEX METACHARACTERS, UNICODE.
 *     No crash, no invention, spans still quote the input exactly.
 *
 *  5. DETERMINISM. analyze(x) twice deep-equals, and A/B/A interleaving
 *     deep-equals too — the second form is the one that catches a module-level
 *     regex whose `lastIndex` survives a call.
 *
 *  6. THE INVENTION GUARD, explicitly. For inputs that state nothing about
 *     currency, channel split, attribution window or performance floor, those
 *     keys are absent from BOTH payloads. Positive controls sit next to each
 *     negative one, because an assertion that cannot fail is not an assertion.
 *
 * Run:
 *
 *   node --test 'packages/brief-engine/test/*.test.ts'
 *
 * The glob, not the bare directory: Node 24.18 does not expand a directory
 * argument to `--test` (it tries to load the directory as a module and dies
 * before any test runs). See the note in emit.test.ts.
 */

import { test, describe } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync, existsSync } from 'node:fs'
import { execFileSync } from 'node:child_process'

import { analyze } from '../src/index.ts'
import type { EngineAnalysis } from '../src/index.ts'
import { FIELDS, FIELD_KEYS, ADCP_FILTER_FIELD_COUNT } from '../src/fields.ts'

